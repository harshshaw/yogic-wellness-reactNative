// Regenerates utils/reel-videos.generated.ts so ReelsScreen never needs to name
// video files explicitly.
//
// The videos stream from Cloud Storage and no longer exist on disk, so this
// reads utils/reel-videos.manifest.json rather than scanning a directory.
// To add a reel: upload the .mp4 to
//   gs://karmana-media-prod/assets/reel-videos/
// then add its filename to the manifest and re-run this script.
const fs = require('fs');
const path = require('path');

const MANIFEST = path.join(__dirname, '..', 'utils', 'reel-videos.manifest.json');
const OUT_FILE = path.join(__dirname, '..', 'utils', 'reel-videos.generated.ts');

let files;
try {
  files = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
} catch (err) {
  console.error(`Cannot read ${MANIFEST}: ${err.message}`);
  process.exit(1);
}

if (!Array.isArray(files) || files.some(f => typeof f !== 'string')) {
  console.error('Manifest must be a JSON array of filenames.');
  process.exit(1);
}

// Refuse to silently empty the reels list — an empty manifest is far more
// likely to be a mistake than an intentional change.
if (files.length === 0) {
  console.error('Manifest is empty; refusing to overwrite the generated list.');
  process.exit(1);
}

files = [...files].sort();

const lines = [
  '// AUTO-GENERATED by scripts/generate-reel-videos.js — do not edit by hand.',
  '// Edit utils/reel-videos.manifest.json instead, then re-run',
  '// `npm run gen:reel-videos` (or `npm start`).',
  '',
  "import { media, type MediaSource } from '../lib/media';",
  '',
  'const reelVideos: MediaSource[] = [',
  ...files.map(f => `  media('reel-videos/${f}'),`),
  '];',
  '',
  'export default reelVideos;',
  '',
];

fs.writeFileSync(OUT_FILE, lines.join('\n'));
console.log(`Generated ${OUT_FILE} with ${files.length} video(s).`);
