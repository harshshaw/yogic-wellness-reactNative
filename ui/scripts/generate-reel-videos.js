// Scans assets/reel-videos and regenerates utils/reel-videos.generated.ts so
// ReelsScreen never needs to name video files explicitly — drop a new .mp4
// in that folder and it shows up automatically the next time Metro starts
// (Metro's require() must be static, so this generates the require list).
const fs = require('fs');
const path = require('path');

const VIDEOS_DIR = path.join(__dirname, '..', 'assets', 'reel-videos');
const OUT_FILE = path.join(__dirname, '..', 'utils', 'reel-videos.generated.ts');

const files = fs
  .readdirSync(VIDEOS_DIR)
  .filter(f => /\.mp4$/i.test(f))
  .sort();

const lines = [
  '// AUTO-GENERATED by scripts/generate-reel-videos.js — do not edit by hand.',
  '// Re-run `npm run gen:reel-videos` (or `npm start`) after adding/removing files',
  '// in assets/reel-videos to refresh this list.',
  '',
  'const reelVideos: ReturnType<typeof require>[] = [',
  ...files.map(f => `  require('../assets/reel-videos/${f}'),`),
  '];',
  '',
  'export default reelVideos;',
  '',
];

fs.writeFileSync(OUT_FILE, lines.join('\n'));
console.log(`Generated ${OUT_FILE} with ${files.length} video(s):`);
files.forEach(f => console.log(`  - ${f}`));
